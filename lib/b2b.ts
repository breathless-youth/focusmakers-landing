/** 개인정보 원칙: 그룹 공부방은 참여자끼리 영상이 직접 오가므로 "영상이 전송되지 않는다"고 쓰지 않는다 */
export const B2B_PRIVACY_LINE =
  "AI 분석에 쓰는 카메라 영상은 기기 밖으로 나가지 않습니다.";

/** 제목 한 줄. 문자열은 그대로, { em }은 강조 색으로 그린다 */
export type HeadlineLine = (string | { em: string })[];

export type Noti = [when: string, title: string, body: string];

export type HeroVisual =
  | {
      type: "report";
      title: string;
      a: string;
      b: string;
      max: number;
      rows: [name: string, total: number, focus: number][];
    }
  | { type: "phone"; from: string; clock: string; notis: Noti[] }
  | {
      type: "cert";
      title: string;
      who: string;
      /** 날짜별 달성 여부. "1"은 달성, "0"은 미달, 뒤쪽 remaining일은 남은 날 */
      days: string;
      remaining: number;
      goal: string;
      done: string;
    }
  | {
      type: "rank";
      title: string;
      rows: [rank: string, name: string, hours: string, me?: boolean][];
      foot: string;
    };

export type Section =
  | {
      t: "proof";
      h: string;
      items: [figure: string, text: string, source: string][];
    }
  | {
      t: "cmp";
      h: string;
      lead?: string;
      left: [title: string, items: string[]];
      right: [title: string, items: string[]];
    }
  | { t: "see"; h: string; lead?: string; yes: string[]; no: string[] }
  | {
      t: "table";
      h: string;
      lead?: string;
      pill: [ok: string, warn: string];
      head: string[];
      rows: [string, string, string, string, string, "ok" | "warn"][];
    }
  | {
      t: "live";
      tag: string;
      h: string;
      lead: string;
      panel: string;
      time: string;
      n: number;
      cols: number;
      unit: string;
      people?: string[];
      keys?: string[];
      /** 첫 항목의 값은 화면에서 지금 집중 중인 수로 바뀐다 */
      stats: [label: string, value: string][];
      feed: [time: string, text: string][];
    }
  | {
      t: "day";
      tag: string;
      h: string;
      sum: [label: string, value: string][];
      /** 24칸 타임라인. f 집중, a 자리 비움, p 폰 사용 */
      pat: string;
      axis: string[];
      keys?: string[];
      from: string;
      clock: string;
      notis: Noti[];
    }
  | {
      t: "digest";
      tag: string;
      h: string;
      from: string;
      clock: string;
      kpis: [value: string, label: string][];
      notis: Noti[];
    }
  | {
      t: "monthly";
      tag: string;
      h: string;
      lead: string;
      kpis: [value: string, label: string][];
      comment: string;
    }
  | {
      t: "member";
      tag: string;
      h: string;
      lead: string;
      from: string;
      clock: string;
      notis: Noti[];
    }
  | { t: "kpi"; tag: string; h: string; kpis: [value: string, label: string][] };

export type Segment = {
  id: string;
  /** 탭과 메타 제목에 쓰는 업종 이름 */
  name: string;
  /** 검색·링크 미리보기용 한 줄 */
  description: string;
  hero: {
    tag: string;
    h: HeadlineLine[];
    sub: string;
    cta: string;
    vis: HeroVisual;
  };
  flow: Section[];
  steps: [title: string, body: string][];
  form: {
    orgLabel: string;
    orgPlaceholder: string;
    sizeLabel: string;
    sizePlaceholder: string;
  };
};

